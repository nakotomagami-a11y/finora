#!/usr/bin/env node
// Generates packages/domain/src/items/items.generated.ts from the Part G table in
// docs/plan/council/01-data.md, the one list behind load rule 2 (architecture §3.6).
//
//   node scripts/gen-items.mjs           write the file
//   node scripts/gen-items.mjs --check   exit 1 if the file is not current (CI)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "docs/plan/council/01-data.md");
const TARGET = join(ROOT, "packages/domain/src/items/items.generated.ts");
const CALLS = ["SHOW", "CAVEAT", "LATER", "HIDE"];

/** Architecture §3.6. PURPOSE is `needs_purpose`; an empty list is "none" (the field does not render). */
export const EMPTY_STATE_KEYS = ["NP", "CN", "NC", "PAID", "LOCK", "KEY", "MANUAL", "AGENT", "PURPOSE"];

/**
 * The empty-state keys of a Part G cell, in order. Quoted copy is dropped first: it is the
 * council's wording for the UI, never a key.
 */
export function emptyStateKeys(cell) {
  const bare = cell.replace(/"[^"]*"/g, " ");
  const keys = [];
  for (const [token] of bare.matchAll(/\b(?:NP|CN|NC|PAID|LOCK|KEY|MANUAL|AGENT|needs_purpose)\b/g)) {
    const key = token === "needs_purpose" ? "PURPOSE" : token;
    if (!keys.includes(key)) keys.push(key);
  }
  return keys;
}

/** The Part G table only: from its heading to the next `## ` heading. */
function partGSection(markdown) {
  const start = markdown.indexOf("## Part G");
  if (start < 0) throw new Error("01-data.md has no Part G");
  const next = markdown.indexOf("\n## ", start + 1);
  return markdown.slice(start, next < 0 ? undefined : next);
}

/**
 * Parses the Part G rows into items. A label in brackets after an id is dropped. An item is
 * personal (purpose gate, disclaimer, TTL) exactly when the council gave it the needs_purpose
 * empty state, and its access tier follows.
 */
export function parsePartG(markdown) {
  const items = [];
  for (const line of partGSection(markdown).split(/\r?\n/)) {
    const cells = line.split("|").map((c) => c.trim());
    if (cells.length < 6 || !/^(?:S\d{2}|M\d{2}|OUT)\./.test(cells[1])) continue;
    const id = cells[1].replace(/\s*\(.*\)\s*$/, "");
    const call = cells[2];
    if (!CALLS.includes(call)) throw new Error(`Part G row ${id}: unknown call "${call}"`);
    const [section, country] = id.split(".");
    const emptyStates = emptyStateKeys(cells[4]);
    const personal = emptyStates.includes("PURPOSE");
    items.push({
      id,
      section,
      country: country.toLowerCase(),
      call: call.toLowerCase(),
      caveatKey: cells[3] === "-" ? null : `items.${id}.caveat`,
      emptyStates,
      personal,
      accessTier: personal ? "purpose" : "open",
      caveatEn: cells[3] === "-" ? null : cells[3],
    });
  }
  const ids = new Set();
  for (const item of items) {
    if (ids.has(item.id)) throw new Error(`Part G lists ${item.id} twice`);
    ids.add(item.id);
  }
  return items;
}

export function render(items) {
  const rows = items.map(({ caveatEn: _, ...item }) => `  ${JSON.stringify(item)},`).join("\n");
  const caveats = items
    .filter((item) => item.caveatEn !== null)
    .map((item) => `  ${JSON.stringify(item.id)}: ${JSON.stringify(item.caveatEn)},`)
    .join("\n");
  return `// Generated by scripts/gen-items.mjs from docs/plan/council/01-data.md, Part G. Do not edit:
// change Part G and run \`pnpm gen:items\`.

export const EMPTY_STATE_KEYS = ${JSON.stringify(EMPTY_STATE_KEYS)} as const;
export type EmptyStateKey = (typeof EMPTY_STATE_KEYS)[number];

export const ITEMS = [
${rows}
] as const;

export type Item = (typeof ITEMS)[number];
export type ItemId = Item["id"];
export type ItemCall = Item["call"];

/** The council's English caveat lines, the source for \`items.<id>.caveat\` in the i18n catalogue. */
export const ITEM_CAVEATS_EN: Readonly<Record<string, string>> = {
${caveats}
};
`;
}

function main() {
  const expected = render(parsePartG(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(TARGET, "utf8");
    } catch {
      // A missing file is stale too.
    }
    if (current !== expected) {
      console.error("gen-items: items.generated.ts is stale. Run `pnpm gen:items` and commit the result.");
      process.exit(1);
    }
    console.log("gen-items: items.generated.ts is current.");
    return;
  }
  writeFileSync(TARGET, expected);
  console.log(`gen-items: wrote ${parsePartG(readFileSync(SOURCE, "utf8")).length} items.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
