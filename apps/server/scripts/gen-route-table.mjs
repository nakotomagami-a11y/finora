#!/usr/bin/env node
// Generates apps/server/src/route-table.ts from the files under src/routes/**/route.ts.
// `route-table.test.ts` fails while the committed table disagrees with the tree.

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SERVER_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const API_PREFIX = "/api";

function* routeFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* routeFiles(path);
    else if (entry.name === "route.ts") yield path;
  }
}

/** `routes/v1/companies/[eid]/route.ts` becomes `/api/v1/companies/:eid`. */
export function patternFor(routesDir, file) {
  const parts = relative(routesDir, dirname(file)).split(/[\\/]/).filter(Boolean);
  const segments = parts.map((part) => (part.startsWith("[") && part.endsWith("]") ? `:${part.slice(1, -1)}` : part));
  return `${API_PREFIX}/${segments.join("/")}`;
}

/** The text of route-table.ts for the routes under `serverRoot/src/routes`. */
export function renderRouteTable(serverRoot = SERVER_ROOT) {
  const routesDir = join(serverRoot, "src", "routes");
  const entries = [...routeFiles(routesDir)]
    .map((file) => ({
      pattern: patternFor(routesDir, file),
      importPath: `./routes/${relative(routesDir, file).split("\\").join("/")}`,
    }))
    .sort((a, b) => a.pattern.localeCompare(b.pattern));
  const imports = entries.map((entry, i) => `import * as route${i} from "${entry.importPath}";`);
  const rows = entries.map((entry, i) => `  { pattern: "${entry.pattern}", module: route${i} },`);
  return [
    "// Generated by `pnpm --filter @finora/server routes`. Do not edit.",
    ...imports,
    'import type { RouteEntry } from "./router-types.ts";',
    "",
    "export const ROUTE_TABLE: readonly RouteEntry[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(join(SERVER_ROOT, "src", "route-table.ts"), renderRouteTable());
  console.log("route-table.ts written");
}
